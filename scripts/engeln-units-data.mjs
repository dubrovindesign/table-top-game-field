/**
 * Ангельн: порядок ячеек = порядок в ENGELN_UNITS (7+7+6).
 * Кубики с карточек: слева направо — красный / зелёный / чёрный / белый.
 */

/** «2/1/1» или «2/3/2/1» → пул кубиков */
export function dicePool(slash) {
  const p = String(slash)
    .split('/')
    .map((x) => parseInt(x, 10) || 0);
  return {
    red: p[0] ?? 0,
    green: p[1] ?? 0,
    black: p[2] ?? 0,
    white: p[3] ?? 0,
  };
}

function z() {
  return { black: 0, green: 0, red: 0, white: 0 };
}

